/** Z tagu axe (napr. "wcag1412") urobí "1.4.12". */
function tagToSc(tag) {
  const m = /^wcag(\d)(\d)(\d+)$/.exec(tag);
  return m ? `${m[1]}.${m[2]}.${m[3]}` : null;
}

